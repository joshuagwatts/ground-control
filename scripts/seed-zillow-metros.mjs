const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36";

function slimRow(r) {
  return {
    name: r.name || "",
    street: r.street || "",
    city: r.city || "",
    state: r.state || "OK",
    zip: r.zip || "",
    lat: r.lat,
    lon: r.lon,
    phone: r.phone || "",
    listingUrl: r.listingUrl || "",
    source: r.source || "zillow-rent",
    phone_kind: "rental",
  };
}

async function fetchHtml(url) {
  const res = await fetch(url, {
    headers: {
      "User-Agent": UA,
      Accept: "text/html,application/xhtml+xml",
      "Accept-Language": "en-US,en;q=0.9",
    },
    redirect: "follow",
  });
  if (!res.ok) throw new Error(`http ${res.status}`);
  return res.text();
}

async function cityRows(city) {
  const out = [];
  const zUrl = formatZillowCityRentUrl(city, "OK");
  if (zUrl) {
    try {
      const html = await fetchHtml(zUrl);
      const rows = parseZillowRentSearchJson(html);
      console.log(`  zillow ${city}: ${rows.length}`);
      out.push(...rows);
    } catch (e) {
      console.log(`  zillow ${city}: FAIL ${e.message}`);
    }
  }
  const rentUrl = formatRentComCityUrl(city, "OK", { kind: "apartments", page: 1 });
  if (rentUrl) {
    try {
      const html = await fetchHtml(rentUrl);
      const rows = parseRentComSearchJson(html);
      console.log(`  rent   ${city}: ${rows.length}`);
      out.push(...rows);
    } catch (e) {
      console.log(`  rent   ${city}: FAIL ${e.message}`);
    }
  }
  const aptUrl = formatApartmentsComCityUrl(city, "OK");
  if (aptUrl) {
    try {
      const html = await fetchHtml(aptUrl);
      const rows = parseApartmentsComSearchHtml(html);
      console.log(`  apts   ${city}: ${rows.length}`);
      out.push(...rows);
    } catch (e) {
      console.log(`  apts   ${city}: FAIL ${e.message}`);
    }
  }
  return out;
}

function loadExisting() {
  try {
    return JSON.parse(fs.readFileSync(outJson, "utf8"));
  } catch {
    return [];
  }
}

const okCities = new Set(OK_RENT_CITY_ROWS.map((r) => String(r.name || "").toLowerCase()));
let flags = Array.isArray(loadExisting()) ? loadExisting() : [];

for (const city of METROS) {
  console.log(city);
  const rows = await cityRows(city);
  flags = mergeRentFlagList(flags, rows);
  await new Promise((r) => setTimeout(r, 400));
}

const slim = mergeRentFlagList([], flags)
  .filter((r) => {
    if (!isOklahomaLatLon(r.lat, r.lon)) return false;
    if (!r.phone && !r.listingUrl) return false;
    const st = String(r.state || "").toUpperCase();
    if (st && st !== "OK") return false;
    return true;
  })
  .map(slimRow);

fs.mkdirSync(path.dirname(outJson), { recursive: true });
fs.writeFileSync(outJson, JSON.stringify(slim));
fs.writeFileSync(
  outJs,
  `/** Generated by scripts/seed-zillow-metros.mjs — dense metro rent pins for Flags. */
export const OK_RENT_FLAG_SEED = ${JSON.stringify(slim)};
export const OK_RENT_FLAG_SEED_AT = ${Date.now()};
`,
);

const byCity = {};
for (const r of slim) {
  const c = r.city || "?";
  byCity[c] = (byCity[c] || 0) + 1;
}
