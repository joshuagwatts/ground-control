/** Statewide Zillow for-rent map pins for Flags — every OK city pop ≥ 1000. */
import fs from "node:fs";
import path from "node:path";
import {
  formatZillowCityRentUrl,
  parseZillowRentSearchJson,
  formatZillowMapBoundsRentUrl,
  mergeRentFlagList,
  isOklahomaLatLon,
} from "../www/contacts.js";
import { OK_RENT_CITY_ROWS } from "../www/ok-rent-cities.js";

const root = path.resolve(import.meta.dirname, "..");
const outJs = path.join(root, "www/ok-rent-flags.js");
const outJson = path.join(root, "www/data/ok-rent-flags.json");
const progressPath = path.join(root, "www/data/ok-rent-zillow-progress.json");

const UA =
  "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/122.0.0.0 Safari/537.36";

function slimRow(r) {
  return {
    name: r.name || "",
    street: r.street || "",
    city: r.city || "",
    state: r.state || "OK",
    zip: r.zip || "",
    lat: r.lat,
    lon: r.lon,
    phone: r.phone || "",
    listingUrl: r.listingUrl || "",
    source: r.source || "zillow-rent",
    phone_kind: "rental",
  };
}

function cityBounds(row, km = 22) {
  const dLat = km / 111.32;
  const dLon = km / (111.32 * Math.max(0.2, Math.cos((row.lat * Math.PI) / 180)));
  return {
    south: row.lat - dLat,
    north: row.lat + dLat,
    west: row.lon - dLon,
    east: row.lon + dLon,
  };
}

async function fetchHtml(url) {
  const res = await fetch(url, {
    headers: {
      "User-Agent": UA,
      Accept: "text/html,application/xhtml+xml",
      "Accept-Language": "en-US,en;q=0.9",
    },
    redirect: "follow",
  });
  if (!res.ok) throw new Error(`http ${res.status}`);
  return res.text();
}

async function cityRows(row) {
  const city = row.name;
  const out = [];
  const mapUrl = formatZillowMapBoundsRentUrl(cityBounds(row, 24));
  if (mapUrl) {
    try {
      const html = await fetchHtml(mapUrl);
      const rows = parseZillowRentSearchJson(html);
      console.log(`  zmap ${city}: ${rows.length}`);
      out.push(...rows);
    } catch (e) {
      console.log(`  zmap ${city}: FAIL ${e.message}`);
    }
  }
  const zUrl = formatZillowCityRentUrl(city, "OK");
  if (zUrl) {
    try {
      const html = await fetchHtml(zUrl);
      const rows = parseZillowRentSearchJson(html);
      console.log(`  zcity ${city}: ${rows.length}`);
      out.push(...rows);
    } catch (e) {
      console.log(`  zcity ${city}: FAIL ${e.message}`);
    }
  }
  return out;
}

function loadExisting() {
  try {
    return JSON.parse(fs.readFileSync(outJson, "utf8"));
  } catch {
    return [];
  }
}

function loadProgress() {
  try {
    const j = JSON.parse(fs.readFileSync(progressPath, "utf8"));
    return {
      done: new Set(Array.isArray(j.done) ? j.done : []),
      flags: Array.isArray(j.flags) ? j.flags : loadExisting(),
    };
  } catch {
    return { done: new Set(), flags: loadExisting() };
  }
}

function writeSeed(flags) {
  const slim = mergeRentFlagList([], flags)
    .filter((r) => {
      if (!isOklahomaLatLon(r.lat, r.lon)) return false;
      if (!r.phone && !r.listingUrl) return false;
      const st = String(r.state || "").toUpperCase();
      if (st && st !== "OK") return false;
      return true;
    })
    .map(slimRow);

  fs.mkdirSync(path.dirname(outJson), { recursive: true });
  const tmpJson = `${outJson}.tmp`;
  const tmpJs = `${outJs}.tmp`;
  fs.writeFileSync(tmpJson, JSON.stringify(slim));
  fs.writeFileSync(
    tmpJs,
    `/** Generated by scripts/seed-zillow-metros.mjs — statewide Zillow rent pins for Flags. */
export const OK_RENT_FLAG_SEED = ${JSON.stringify(slim)};
export const OK_RENT_FLAG_SEED_AT = ${Date.now()};
`,
  );
  fs.renameSync(tmpJson, outJson);
  fs.renameSync(tmpJs, outJs);
  return slim;
}

function saveProgress(done, flags) {
  fs.mkdirSync(path.dirname(progressPath), { recursive: true });
  fs.writeFileSync(progressPath, JSON.stringify({ done: [...done], flags, at: Date.now() }));
  writeSeed(flags);
}

const cities = OK_RENT_CITY_ROWS.filter((r) => r.pop >= 1000).sort((a, b) => b.pop - a.pop);
const { done, flags: startFlags } = loadProgress();
let flags = Array.isArray(startFlags) ? startFlags : [];

console.log(`Seeding ${cities.length} OK cities (pop ≥ 1000)… ${done.size} done · ${flags.length} pins`);

for (const row of cities) {
  const key = String(row.name || "").toLowerCase();
  if (done.has(key)) {
    console.log(`skip ${row.name}`);
    continue;
  }
  console.log(row.name);
  const rows = await cityRows(row);
  flags = mergeRentFlagList(flags, rows);
  done.add(key);
  saveProgress(done, flags);
  await new Promise((r) => setTimeout(r, 280));
}

const slim = writeSeed(flags);
try {
  fs.unlinkSync(progressPath);
} catch {
  /* ok */
}

const byCity = {};
for (const r of slim) {
  const c = r.city || "?";
  byCity[c] = (byCity[c] || 0) + 1;
}
console.log("TOTAL", slim.length, "· phones", slim.filter((r) => r.phone).length);
console.log(
  Object.entries(byCity)
    .sort((a, b) => b[1] - a[1])
    .slice(0, 25)
    .map(([c, n]) => `${c}:${n}`)
    .join("\n"),
);
