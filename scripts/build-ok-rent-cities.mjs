/** Build www/ok-rent-cities.js from US cities CSV ∩ OK municipalities (pop ≥ 1000). */
import fs from "node:fs";
import path from "node:path";
import https from "node:https";

const root = path.resolve(import.meta.dirname, "..");
const outJson = path.join(root, "www/data/ok-rent-cities.json");
const outJs = path.join(root, "www/ok-rent-cities.js");
const wikiPath = path.join(
  process.env.USERPROFILE || "",
  ".cursor/projects/c-Users-joshu-GroundControl/agent-tools/60cab801-7338-4ff5-a1f9-7cc065692258.txt",
);
const csvUrl = "https://raw.githubusercontent.com/kelvins/US-Cities-Database/main/csv/us_cities.csv";

function fetchText(u) {
  return new Promise((resolve, reject) => {
    https
      .get(u, (res) => {
        if (res.statusCode && res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
          fetchText(res.headers.location).then(resolve, reject);
          return;
        }
        if (res.statusCode !== 200) {
          reject(new Error(`HTTP ${res.statusCode}`));
          return;
        }
        const chunks = [];
        res.on("data", (c) => chunks.push(c));
        res.on("end", () => resolve(Buffer.concat(chunks).toString("utf8")));
      })
      .on("error", reject);
  });
}

function parseCsvLine(line) {
  const parts = [];
  let cur = "";
  let q = false;
  for (const ch of line) {
    if (ch === '"') {
      q = !q;
      continue;
    }
    if (ch === "," && !q) {
      parts.push(cur);
      cur = "";
      continue;
    }
    cur += ch;
  }
  parts.push(cur);
  return parts;
}

function slug(s) {
  return String(s || "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "");
}

/** Municipality names with 2024 pop ≥ 1000 from the Wikipedia dump. */
function wikiCities() {
  const text = fs.readFileSync(wikiPath, "utf8");
  const out = new Map(); // slug -> { name, pop }
  for (const line of text.split(/\n/)) {
    // | 40 | Woodward | City | Woodward | | 11,750 | 12,133 | −3.16% |
    const m = line.match(
      /^\|\s*\d+\s*\|\s*([^|]+?)\s*\|\s*(City|Town)\s*\|[^|]*\|[^|]*\|\s*([\d,]+)/i,
    );
    if (!m) continue;
    const name = m[1].trim().replace(/\s+/g, " ");
    const pop = Number(String(m[3]).replace(/,/g, ""));
    if (!name || !Number.isFinite(pop) || pop < 1000) continue;
    out.set(slug(name), { name, pop });
  }
  return out;
}

const wanted = wikiCities();
if (wanted.size < 100) throw new Error(`wiki parse too small: ${wanted.size}`);

const csv = await fetchText(csvUrl);
const bySlug = new Map();
for (const line of csv.trim().split(/\r?\n/).slice(1)) {
  const parts = parseCsvLine(line);
  if (parts[1] !== "OK") continue;
  const name = String(parts[3] || "").trim();
  const lat = Number(parts[5]);
  const lon = Number(parts[6]);
  if (!name || !Number.isFinite(lat) || !Number.isFinite(lon)) continue;
  bySlug.set(slug(name), {
    name,
    lat: Math.round(lat * 1e5) / 1e5,
    lon: Math.round(lon * 1e5) / 1e5,
  });
}

// Aliases for Rent.com / apartments.com path quirks.
const aliases = {
  pryorcreek: "Pryor",
  newcordell: "Cordell",
};

const rows = [];
const seen = new Set();
for (const [key, meta] of wanted) {
  let hit = bySlug.get(key);
  if (!hit && key === "pryorcreek") hit = bySlug.get("pryorcreek") || bySlug.get("pryor");
  if (!hit) {
    // Try dropping "city"/"creek" suffixes already normalized.
    continue;
  }
  const listingName = aliases[key] || meta.name;
  const sk = slug(listingName);
  if (seen.has(sk)) continue;
  seen.add(sk);
  rows.push({
    name: listingName,
    lat: hit.lat,
    lon: hit.lon,
    pop: meta.pop,
  });
}

// Ensure county-seat / rental hubs that wiki named differently still land.
for (const extra of [
  { name: "Pryor", lat: 36.3084, lon: -95.3169, pop: 9700 },
  { name: "Cordell", lat: 35.2906, lon: -98.9884, pop: 2744 },
]) {
  const sk = slug(extra.name);
  if (seen.has(sk)) continue;
  seen.add(sk);
  rows.push(extra);
}

rows.sort((a, b) => b.pop - a.pop || a.name.localeCompare(b.name));
fs.mkdirSync(path.dirname(outJson), { recursive: true });
fs.writeFileSync(outJson, `${JSON.stringify(rows)}\n`);
fs.writeFileSync(
  outJs,
  `/** Generated by scripts/build-ok-rent-cities.mjs — Oklahoma municipalities (pop ≥ 1000) for Flags. */\nexport const OK_RENT_CITY_ROWS = ${JSON.stringify(rows)};\n`,
);
console.log(`wrote ${rows.length} OK municipalities → ${path.relative(root, outJs)}`);
console.log(
  "sample",
  rows
    .filter((r) => /Woodward|Guymon|Tulsa|Edmond|Boise|Kenton/i.test(r.name))
    .map((r) => r.name)
    .join(", "),
);
