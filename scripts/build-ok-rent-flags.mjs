/** Build www/ok-rent-flags.js — statewide Rent.com leasing phones for Flags (map-view seed). */
import fs from "node:fs";
import path from "node:path";
import {
  formatRentComCityUrl,
  formatApartmentsComCityUrl,
  parseRentComSearchJson,
  parseApartmentsComSearchHtml,
  mergeRentFlagList,
  isOklahomaLatLon,
} from "../www/contacts.js";
import { OK_RENT_CITY_ROWS } from "../www/ok-rent-cities.js";
import { listingBrowserHeaders } from "../www/device.js";
import { httpGet } from "../www/net.js";

const root = path.resolve(import.meta.dirname, "..");
const outJs = path.join(root, "www/ok-rent-flags.js");
const outJson = path.join(root, "www/data/ok-rent-flags.json");
const progressPath = path.join(root, "www/data/ok-rent-flags-progress.json");

const DELAY_MS = 3500;
const RETRY_EMPTY = 1;

function sleep(ms) {
  return new Promise((r) => setTimeout(r, ms));
}

function slimRow(r) {
  return {
    name: r.name || "",
    street: r.street || "",
    city: r.city || "",
    state: r.state || "OK",
    zip: r.zip || "",
    lat: r.lat,
    lon: r.lon,
    phone: r.phone,
    listingUrl: r.listingUrl || "",
    source: r.source || "rent-com",
    phone_kind: "rental",
  };
}

function loadProgress() {
  try {
    const j = JSON.parse(fs.readFileSync(progressPath, "utf8"));
    return {
      done: new Set(Array.isArray(j.done) ? j.done : []),
      flags: Array.isArray(j.flags) ? j.flags : [],
    };
  } catch {
    try {
      const flags = JSON.parse(fs.readFileSync(outJson, "utf8"));
      return { done: new Set(), flags: Array.isArray(flags) ? flags : [] };
    } catch {
      return { done: new Set(), flags: [] };
    }
  }
}

function saveProgress(done, flags) {
  fs.mkdirSync(path.dirname(progressPath), { recursive: true });
  fs.writeFileSync(
    progressPath,
    JSON.stringify({ done: [...done], flags, at: Date.now() }),
  );
  writeSeed(flags);
}

function writeSeed(flags) {
  const okCities = new Set(OK_RENT_CITY_ROWS.map((r) => String(r.name || "").toLowerCase()));
  const slim = mergeRentFlagList([], flags)
    .filter((r) => {
      if (!isOklahomaLatLon(r.lat, r.lon)) return false;
      const st = String(r.state || "").toUpperCase();
      if (st && st !== "OK") return false;
      const city = String(r.city || "").toLowerCase();
      if (city && okCities.has(city)) return true;
      // Keep if labeled OK / empty state and inside the state box.
      return !st || st === "OK";
    })
    .map(slimRow);
  fs.mkdirSync(path.dirname(outJson), { recursive: true });
  fs.writeFileSync(outJson, JSON.stringify(slim));
  fs.writeFileSync(
    outJs,
    `/** Generated by scripts/build-ok-rent-flags.mjs — statewide Rent.com / apartments phones for Flags. */
export const OK_RENT_FLAG_SEED = ${JSON.stringify(slim)};
export const OK_RENT_FLAG_SEED_AT = ${Date.now()};
`,
  );
  return slim.length;
}

async function fetchHtml(url) {
  try {
    const { body } = await httpGet(url, 28000, listingBrowserHeaders());
    return String(body || "");
  } catch {
    return "";
  }
}

async function cityFlags(city) {
  const state = "OK";
  const acc = [];
  for (const kind of ["apartments", "houses"]) {
    const url = formatRentComCityUrl(city, state, { kind, page: 1 });
    if (!url) continue;
    let list = [];
    for (let attempt = 0; attempt <= RETRY_EMPTY; attempt++) {
      const html = await fetchHtml(url);
      list = parseRentComSearchJson(html);
      if (list.length) break;
      if (attempt < RETRY_EMPTY) await sleep(DELAY_MS);
    }
    acc.push(...list);
    await sleep(800);
  }
  const aptUrl = formatApartmentsComCityUrl(city, state);
  if (aptUrl) {
    const html = await fetchHtml(aptUrl);
    acc.push(...parseApartmentsComSearchHtml(html));
  }
  return mergeRentFlagList([], acc).map(slimRow);
}

// West → east so panhandle / west OK aren't starved behind OKC rate limits.
const cities = OK_RENT_CITY_ROWS.slice().sort((a, b) => a.lon - b.lon || a.lat - b.lat);
const { done, flags } = loadProgress();
let acc = flags.slice();

console.log(`resume: ${done.size} cities done, ${acc.length} flags so far, ${cities.length} total cities`);

for (const row of cities) {
  const key = String(row.name || "").toLowerCase();
  if (done.has(key)) continue;
  process.stdout.write(`scraping ${row.name}… `);
  const rows = await cityFlags(row.name);
  console.log(`${rows.length} phones`);
  acc = mergeRentFlagList(acc, rows);
  done.add(key);
  saveProgress(done, acc);
  await sleep(DELAY_MS);
}

const n = writeSeed(acc);
console.log(`wrote ${n} statewide flags → ${outJs}`);
try {
  fs.unlinkSync(progressPath);
} catch {
  /* ok */
}
